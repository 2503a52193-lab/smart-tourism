def add_hotels_to_db():
    from app import app, db, Destination, Hotel, HotelProfile, RoomType
    from sqlalchemy import func

    with app.app_context():
        added_hotels = 0
        added_rooms = 0

        for h in ADDITIONAL_HOTELS:
            dest = Destination.query.filter(func.lower(Destination.name) == h["destination"].casefold()).first()
            if not dest:
                print(f"Warning: destination {h['destination']} not found!")
                continue

            hotel = Hotel.query.filter(
                Hotel.destination_id == dest.id,
                func.lower(Hotel.name) == h["name"].casefold(),
            ).first()

            rate = Decimal(str(h["nightly_rate"]))
            if not hotel:
                hotel = Hotel(
                    destination_id=dest.id,
                    name=h["name"],
                    nightly_rate=rate,
                    price_tier=h.get("price_tier", "mid-range"),
                    price_basis="estimate",
                    is_demo=True,
                    source_url="",
                    address=h["address"],
                    image_url=h["image_url"],
                    description=h["description"],
                    check_in_policy=h.get("check_in_policy", "14:00"),
                    check_out_policy=h.get("check_out_policy", "11:00"),
                    active=True,
                )
                db.session.add(hotel)
                db.session.flush()

                hotel.profile = HotelProfile(
                    hotel_id=hotel.id,
                    rating=h["rating"],
                    rating_verified=False,
                    facilities=h["facilities"],
                )
                added_hotels += 1
            else:
                hotel.nightly_rate = rate
                hotel.address = h["address"]
                hotel.image_url = h["image_url"]
                hotel.description = h["description"]
                hotel.active = True
                if hotel.profile:
                    hotel.profile.rating = h["rating"]
                    hotel.profile.facilities = h["facilities"]
                else:
                    hotel.profile = HotelProfile(
                        hotel_id=hotel.id,
                        rating=h["rating"],
                        rating_verified=False,
                        facilities=h["facilities"],
                    )

            for r in h["rooms"]:
                room = RoomType.query.filter(
                    RoomType.hotel_id == hotel.id,
                    func.lower(RoomType.name) == r["name"].casefold(),
                ).first()
                r_rate = Decimal(str(r["nightly_rate"]))
                if not room:
                    room = RoomType(
                        hotel_id=hotel.id,
                        name=r["name"],
                        nightly_rate=r_rate,
                        capacity=r["capacity"],
                        available_rooms=r["available_rooms"],
                        total_rooms=r["total_rooms"],
                        price_basis="estimate",
                        active=True,
                    )
                    db.session.add(room)
                    added_rooms += 1
                else:
                    room.nightly_rate = r_rate
                    room.capacity = r["capacity"]
                    room.available_rooms = r["available_rooms"]
                    room.total_rooms = r["total_rooms"]
                    room.active = True

        db.session.commit()
        print(f"Successfully added/verified {added_hotels} hotels and {added_rooms} rooms in the database.")

        # Summary of hotels per destination
        dests = Destination.query.all()
        for d in dests:
            hotels = Hotel.query.filter_by(destination_id=d.id, active=True).all()
            print(f"Destination {d.id} ({d.name}): {len(hotels)} hotels")

if __name__ == "__main__":
    add_hotels_to_db()
