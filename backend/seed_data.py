def seed_transport_catalog(database):
    """Seed comprehensive verified and realistic demo transport routes across India for bus and train (taxi removed)."""
    from datetime import date
    from sqlalchemy import text
    
    # 1. Clean up / deactivate any leftover taxi records completely
    try:
        database.session.execute(text("UPDATE transport_service SET active = 0 WHERE LOWER(mode) IN ('taxi', 'transfer', 'cab')"))
        database.session.commit()
    except Exception:
        database.session.rollback()

    counts = {"transport_routes_added": 0, "transport_routes_updated": 0}
    try:
        from transport_generator import seed_all_destination_demo_transport
        gen_counts = seed_all_destination_demo_transport(database, Destination, TransportService)
        counts["transport_routes_added"] += gen_counts.get("total_new_services", 0)
    except Exception:
        pass
    
    for item in TRANSPORT_ROUTES_DATA:
        dest_obj = Destination.query.filter(
            func.lower(Destination.name) == item["destination"].casefold()
        ).first()
        dest_id = dest_obj.id if dest_obj else None

        existing = TransportService.query.filter(
            TransportService.mode == item["mode"],
            func.lower(TransportService.operator) == item["operator"].casefold(),
            func.lower(TransportService.origin) == item["origin"].casefold(),
            func.lower(TransportService.destination) == item["destination"].casefold(),
            TransportService.departure_time == item["departure_time"],
        ).first()

        fare = Decimal(str(item["ticket_price"]))
        service_date = date.today()

        if existing is None:
            new_srv = TransportService(
                destination_id=dest_id,
                mode=item["mode"],
                operator=item["operator"],
                service_name=item.get("service_name", ""),
                service_type=item.get("service_type", ""),
                origin=item["origin"],
                origin_station=item.get("origin_station", ""),
                destination=item["destination"],
                destination_station=item.get("destination_station", ""),
                boarding_point=item.get("boarding_point", ""),
                dropping_point=item.get("dropping_point", ""),
                booking_status=item.get("booking_status", "Available"),
                departure_time=item["departure_time"],
                arrival_time=item["arrival_time"],
                duration=item.get("duration", ""),
                distance_km=item.get("distance_km", ""),
                available_classes=item.get("available_classes", ""),
                class_fares=item.get("class_fares", {}),
                pricing_unit=item.get("pricing_unit", "per_person"),
                contact_number=item.get("contact_number", ""),
                booking_url=item.get("booking_url", ""),
                source_url=item.get("booking_url", ""),
                is_daily=item.get("is_daily", True),
                service_date=service_date,
                ticket_price=fare,
                available_seats=item.get("available_seats"),
                availability_verified=item.get("availability_verified", True),
                price_basis=item.get("price_basis", "estimate"),
                is_demo=item.get("is_demo", True),
                active=True,
            )
            database.session.add(new_srv)
            counts["transport_routes_added"] += 1
        else:
            existing.destination_id = dest_id or existing.destination_id
            existing.service_name = item.get("service_name", existing.service_name)
            existing.service_type = item.get("service_type", existing.service_type)
            existing.origin_station = item.get("origin_station", existing.origin_station)
            existing.destination_station = item.get("destination_station", existing.destination_station)
            existing.boarding_point = item.get("boarding_point", getattr(existing, "boarding_point", ""))
            existing.dropping_point = item.get("dropping_point", getattr(existing, "dropping_point", ""))
            existing.booking_status = item.get("booking_status", getattr(existing, "booking_status", "Available"))
            existing.departure_time = item["departure_time"]
            existing.arrival_time = item["arrival_time"]
            existing.duration = item.get("duration", existing.duration)
            existing.distance_km = item.get("distance_km", existing.distance_km)
            existing.available_classes = item.get("available_classes", existing.available_classes)
            existing.class_fares = item.get("class_fares", existing.class_fares)
            existing.pricing_unit = item.get("pricing_unit", "per_person")
            existing.contact_number = item.get("contact_number", existing.contact_number)
            existing.booking_url = item.get("booking_url", existing.booking_url)
            existing.source_url = item.get("booking_url", existing.source_url)
            existing.is_daily = item.get("is_daily", True)
            existing.ticket_price = fare
            existing.available_seats = item.get("available_seats", existing.available_seats)
            existing.availability_verified = item.get("availability_verified", True)
            existing.price_basis = item.get("price_basis", "estimate")
            existing.is_demo = item.get("is_demo", True)
            existing.active = True
            counts["transport_routes_updated"] += 1

    database.session.commit()
    return counts
