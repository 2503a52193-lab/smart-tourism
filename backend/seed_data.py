def clear_hotel_place_catalog(database):
    """Delete unbooked hotel data and places; archive hotels with booking history."""
    counts = {"hotels deleted": 0, "booked hotels archived": 0, "places deleted": 0}
    booked_hotel_ids = {
        hotel_id for (hotel_id,) in database.session.query(Booking.hotel_id).distinct()
    }

    for hotel in Hotel.query.all():
        if hotel.id in booked_hotel_ids:
            hotel.active = False
            for room in hotel.rooms:
                room.active = False
            counts["booked hotels archived"] += 1
        else:
            database.session.delete(hotel)
            counts["hotels deleted"] += 1

    counts["places deleted"] = database.session.query(TouristAttraction).delete()
    database.session.commit()
    return counts


