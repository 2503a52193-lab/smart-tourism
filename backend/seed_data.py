def seed_destinations_and_attractions(database):
    """Repeatable seed function to populate the 15 destinations and their tourist attractions without creating duplicates."""
    dest_counts = {"added": 0, "existing": 0}
    place_counts = {"added": 0, "existing": 0}

    destination_map = {}

    for d in DESTINATIONS_DATA:
        dest = Destination.query.filter(func.lower(Destination.name) == d["name"].casefold()).first()
        if dest is None:
            dest = Destination(
                name=d["name"],
                state=d["state"],
                region=d["region"],
                description=d["description"],
                image_url=d["image_url"],
                best_time_to_visit=d["best_time_to_visit"],
                budget_range=d["budget_range"],
                active=True,
            )
            database.session.add(dest)
            database.session.flush()
            dest_counts["added"] += 1
        else:
            # Update fields to ensure verified data
            dest.state = d["state"]
            dest.region = d["region"]
            dest.description = d["description"]
            dest.image_url = d["image_url"]
            dest.best_time_to_visit = d["best_time_to_visit"]
            dest.budget_range = d["budget_range"]
            dest.active = True
            dest_counts["existing"] += 1

        destination_map[d["name"].casefold()] = dest

    database.session.commit()

    # Seed attractions
    for a in ATTRACTIONS_DATA:
        dest_key = a["destination_name"].casefold()
        dest = destination_map.get(dest_key)
        if not dest:
            dest = Destination.query.filter(func.lower(Destination.name) == dest_key).first()
        if not dest:
            continue

        place = TouristAttraction.query.filter(
            TouristAttraction.destination_id == dest.id,
            func.lower(TouristAttraction.name) == a["name"].casefold()
        ).first()

        if place is None:
            place = TouristAttraction(
                destination_id=dest.id,
                name=a["name"],
                description=a["description"],
                category=a["category"],
                image_url=a["image_url"],
                duration_hours=a["duration_hours"],
                opening_hours=a["opening_hours"],
                entry_fee=Decimal(str(a["entry_fee"])),
                estimated_cost=Decimal(str(a["entry_fee"])),
                latitude=a.get("latitude"),
                longitude=a.get("longitude"),
                best_time_to_visit=a.get("best_time_to_visit", ""),
                verification_status=a.get("verification_status", "verified"),
                cost_basis="free" if a["entry_fee"] == 0 else "verified",
                source_url=a.get("source_url", ""),
                active=True,
            )
            database.session.add(place)
            place_counts["added"] += 1
        else:
            place.description = a["description"]
            place.category = a["category"]
            place.image_url = a["image_url"]
            place.duration_hours = a["duration_hours"]
            place.opening_hours = a["opening_hours"]
            place.entry_fee = Decimal(str(a["entry_fee"]))
            place.estimated_cost = Decimal(str(a["entry_fee"]))
            place.latitude = a.get("latitude")
            place.longitude = a.get("longitude")
            place.best_time_to_visit = a.get("best_time_to_visit", "")
            place.verification_status = a.get("verification_status", "verified")
            place.cost_basis = "free" if a["entry_fee"] == 0 else "verified"
            place.source_url = a.get("source_url", "")
            place.active = True
            place_counts["existing"] += 1

    database.session.commit()
    return {
        "destinations": dest_counts,
        "places": place_counts,
    }


